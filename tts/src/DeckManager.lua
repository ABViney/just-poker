function gatherCards(onFinish_params)
  local cards_on_table = {}
  -- Hopin that the group method will group to the first index in the collection provided
  if Deck then table.insert(cards_on_table, Deck) end
  for object in getObjects() do
    if object.type == "Card" or object.type == "Deck" then
      table.insert(cards_on_table, object)
    end
  end
  
  PlayerManager.call("removeCardsFromPlayerHoles")

  local collection = group(cards_on_table)
  collection[1].setPositionSmooth(DeckZone.getPosition(), false, false)
  collection[1].setRotationSmooth(DeckZone.getRotation(), false, false)

  Wait.time(
    function() onFinish_params.service.call(onFinish_params.callback, onFinish_params.args) end,
    GATHER_CARDS_DELAY
  )
end

--[[
  params = {
    player = <Player>,
    onFinish_params = {
      service  = <Scripting Zone>,
      callback = string,
      args     = table
    }
  }
]]
function movePlayerCardsToReflectIntent(params)
  local player = params.player
  local onFinish_params = params.onFinish_params

  

  if player.state ~= "fold" and player.state ~= "show" then  
    -- Nothing to do, issue the callback
    onFinish_params.service.call(onFinish_params.callback, onFinish_params.args)
    return
  end

  local blind_zone = player.zones.blind_zone -- Safest place to lay cards
  local rotation   = player.zones.blind_zone.getRotation()
  local scale      = player.zones.blind_zone.getScale()

  local card_in_transit = true
  function noCardInTransit() return not card_in_transit end

  local is_face_up = player.state ~= "fold"
  local positionY = player.zones.blind_zone.getPosition().y
  local positions = {
    blind_zone.positionToWorld({-1/scale.x, -positionY, 0}),
    blind_zone.positionToWorld({1/scale.x, positionY, 0})
  }
  local index = 1
  card_in_transit = true
  for card in player.hole do
    if not is_face_up then card.flip() end
    local position = positions[index]
    Wait.time(
      function()
        card.use_hands = false
        card.setPositionSmooth(position, false, true)
        Wait.time(function() card.use_hands = true end, 1)
      end,
      0.5
    )
    index = index + 1
  end

  Wait.time(
    function()
      card_in_transit = false
    end,
    1.2
  )

  Wait.condition(
    function() onFinish_params.service.call(onFinish_params.callback, onFinish_params.args) end,
    noCardInTransit
  )
end

