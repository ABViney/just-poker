--[[
    If a deck is in the zone, this function will return an ordered 
    array of all the cards in the deck.
--]]
function getCardsInDeck()
  if Deck == nil then
    broadcastToAll("Error: Could not find deck!\nMove deck to dealer zone if one exists.", {r=0, g=1, b=1})
    return nil -- We don't have a deck to get the card order of
  end

  -- https://stackoverflow.com/questions/1426954/split-string-in-lua
  function split_memo(card)
    local t = {}
    for k,_ in string.gmatch(card.memo, ".") do
      t[#t+1] = k
    end
    return {
      rank = string.byte(t[1]),
      suit = string.byte(t[2])
    }
  end

  local cards_in_deck = Deck.getObjects()
  local card_order = {}
  for card, _ in cards_in_deck do
    card_order[card.index+1] = split_memo(card)
  end
  log(JSON.encode(card_order))

  return nil
end

--[[
  deal_data: {
    -- "rank" and "suite" are ascii char values. The Go server we 
    -- use stores these fields as "runes" which are essentially chars.
    -- We need to convert these to characters in order to locate cards.
    cards: [{rank: int, suite: int}, {rank: int, suite: int}, ...]
    
    position: {x: float, y: float, z: float} -- Where to put the cards after they're removed from the deck

    is_face_up: bool
  }
]]
function dealCards(deal_data)
  local cards_to_find = {}
  for card in deal_data.cards do
    cards_to_find[#cards_to_find+1] = string.char(card.rank) .. string.char(card.suit)
  end

  local cards_dealt = {}

  for card_to_find in cards_to_find do
    for card in Deck.getObjects() do
      if card.memo == card_to_find then

        local card_instance = Deck.takeObject({
          guid = card.guid,
          position = deal_data.position,
          -- Only rotation value that matters is Y
          -- if the rotation has the card face up it can be seen before it should
          rotation = {0, deal_data.rotation.y, 180},
          callback_function = function(taken_card)
            -- Flipping in this callback makes sure the cards arrive to their
            -- destination before becoming visible (e.g. the player's hand)
            if deal_data.is_face_up then taken_card.flip() end
          end
        })
        table.insert(cards_dealt, card_instance)
      end
    end
  end
  return cards_dealt
end

--[[
    All fields are optional. Sets the street and discard pile.
    street_data: {
        discard: [{rank: int, suite: int}], ...}]   // (Max 3)
        street: [{rank: int, suite: int}, ...] // (Max 5)
    }
--]]
function setStreet(table)

  local street_data = table.street

  if street_data.discard then
    local deal_data = {
      cards = {},
      position = DiscardPosition,
      is_face_up = false
    }
    for card_data in street_data.discard do
      deal_data.cards[#deal_data.cards+1] = string.char(card_data.rank) .. string.char(card_data.suite)
    end
    dealCards(deal_data)
  end

  if street_data.street then
    local street_index = 1
    for card_data in street_data.street do
      if (street_index > #StreetPositions) then
        log("Error: More cards in the street than can exist.")
        log(street_data.street)
        break
      end
      dealCards({
        cards = {card_data},
        position = StreetPositions[street_index],
        is_face_up = true
      })
      street_index = street_index + 1
    end
  end
end

--[[
  Deals two cards to each player still in the game, starting from the first player to the
  left of the DealerButton that is not "out".

  onFinish_params = {
    service   = <Scripting Zone>,
    callback  = string (function name in service's script),
    args      = table (arguments to pass to callback)
  }
--]]
function dealHand(onFinish_params)
  -- Internal mutex for delaying the dealing of another card until the preceding
  -- one has finished moving
  local card_in_transit = false
  function noCardInTransit() return not card_in_transit end

  local deal_starts_from = PlayerManager.call("getPlayerByPosition", BlindManager.getVar("DealerButtonPosition"))
  log("Deal starts from: " .. deal_starts_from.display_name)
  local current_player_being_dealt = PlayerManager.call("getNextValidPlayer", deal_starts_from)

  function dealCardToPlayer()
    if #current_player_being_dealt.hole >= 2 then
      --[[
        dealHand returns much sooner than the final card is dealt.
        onFinish_params contains information for a function to call when this
        function's operations complete, which i'm using to disable a mutex set
        in TurnManager
      --]] 
      
      Wait.condition(
        function()
          onFinish_params.service.call(onFinish_params.callback)
        end,
        noCardInTransit
      )
      return
    end

    card_in_transit = true
    local dealt_card = Deck.takeObject({
      position = current_player_being_dealt.zones.hand_zone.getPosition(),
      rotation =  {x=0, y=current_player_being_dealt.zones.hand_zone.getRotation().y, z=180},
      top = true,
      smooth = true,
      callback_function = function(card)
        card.flip()
        card_in_transit = false
      end
    })
    PlayerManager.call("addCardToPlayerHole", {position = current_player_being_dealt.position, card = dealt_card})
    current_player_being_dealt = PlayerManager.call("getNextValidPlayer", current_player_being_dealt)

    Wait.condition(
      dealCardToPlayer,
      noCardInTransit
    )
  end

  function dealCards()
