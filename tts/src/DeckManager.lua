    )
  end

  dealCards()

  return true
end

function burnCard()
  lockExternalScriptMutex()
  Deck.takeObject({
    position = DiscardPosition,
    rotation =  {x=0, y=0, z=180},
    top = true,
    callback_function = function(card)
      unlockExternalScriptMutex()
    end
  })
end

function dealFlop(onFinish_params)
  -- burn one card
  -- deal 3 cards onto the street 
  burnCard()

  local index = 1
  for i=1, 3 do
    local pos = i
    Wait.condition(
      function()
        lockExternalScriptMutex()
        Deck.takeObject({
          position = StreetPositions[pos],
          rotation = {0, 0, 180},
          top = true,
          callback_function = function(card)
            unlockExternalScriptMutex()
            card.flip()
            index = index + 1
          end
        })

        if index == 3 then
          Wait.condition(
            function()
              onFinish_params.service.call(onFinish_params.callback, onFinish_params.args)
            end,
            isExternalScriptMutexUnlocked
          )
        end
      end,
      function() return isExternalScriptMutexUnlocked() and index == i end
    )
  end
end

