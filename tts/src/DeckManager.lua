function onObjectSpawn(object)
  if Deck == nil and object.type == "Deck" then
    log("Deck found!")
    Deck = object
  end
end

function onObjectDestroy(object)
  if Deck == nil then return end
  if object.guid == Deck.guid then
    log("Deck lost!")
    Deck = nil
    -- This event fires if the dealer stacks the original deck
    -- onto a different one. This happens after the onObjectSpawn
    -- event fires for the new deck, so we have to look for it.
    for object in getAllObjects() do
      if object.type == "Deck" then
        log("Deck found!")
        Deck = object
        break;
      end
    end
  end
end

function onObjectEnterScriptingZone(zone, enter_object)
    -- To simplify life, if a deck enters this zone, it's the dealer's deck.
    if zone == DeckZone and Deck == nil and enter_object.type == "Deck" then
        log("Deck found!")
        Deck = enter_object
    end
end

